use std::fmt::Write as _;
use std::fs;
use std::path::Path;

fn main() {
    let posts_dir = Path::new("posts");

    // Re-run if any .md file changes or is added
    println!("cargo:rerun-if-changed=posts");

    let mut entries: Vec<(String, String, String, String, String)> = Vec::new();
    // (slug, title, date, description, rel_path)

    if posts_dir.is_dir() {
        let mut paths: Vec<_> = fs::read_dir(posts_dir)
            .expect("cannot read posts/")
            .filter_map(|e| e.ok())
            .filter(|e| e.path().extension().map_or(false, |x| x == "md"))
            .map(|e| e.path())
            .collect();

        // Stable order: newest date first (sorted by filename descending)
        paths.sort_by(|a, b| b.cmp(a));

        for path in &paths {
            println!("cargo:rerun-if-changed={}", path.display());

            let src = fs::read_to_string(path).expect("cannot read post");
            let (title, date, description) = parse_frontmatter(&src);
            let slug = path
                .file_stem()
                .unwrap()
                .to_string_lossy()
                .into_owned();
            let rel = format!(
                "{}/posts/{}",
                std::env::var("CARGO_MANIFEST_DIR").unwrap(),
                path.file_name().unwrap().to_string_lossy()
            );
            entries.push((slug, title, date, description, rel));
        }
    }

    // Generate the Rust source
    let mut out = String::from(
        "// AUTO-GENERATED by build.rs — do not edit manually.\n\
         struct PostMeta {\n\
             slug: &'static str,\n\
             title: &'static str,\n\
             date: &'static str,\n\
             description: &'static str,\n\
             body: &'static str,\n\
         }\n\n\
         const POSTS: &[PostMeta] = &[\n",
    );

    for (slug, title, date, desc, rel) in &entries {
        write!(
            out,
            "    PostMeta {{ slug: {slug:?}, title: {title:?}, date: {date:?}, \
             description: {desc:?}, body: include_str!({rel:?}) }},\n",
        )
        .unwrap();
    }

    out.push_str("];\n");

    let out_dir = std::env::var("OUT_DIR").unwrap();
    fs::write(format!("{out_dir}/posts_generated.rs"), out)
        .expect("cannot write posts_generated.rs");
}

/// Extracts title/date/description from YAML frontmatter (`--- ... ---`).
/// Returns empty strings for missing fields — no panic.
fn parse_frontmatter(src: &str) -> (String, String, String) {
    let s = src.trim_start();
    if !s.starts_with("---") {
        return (String::new(), String::new(), String::new());
    }
    let rest = &s[3..];
    let fm = if let Some(end) = rest.find("\n---") {
        &rest[..end]
    } else {
        return (String::new(), String::new(), String::new());
    };

    let mut title = String::new();
    let mut date = String::new();
    let mut description = String::new();

    for line in fm.lines() {
        if let Some(v) = line.strip_prefix("title:") {
            title = v.trim().trim_matches('"').to_string();
        } else if let Some(v) = line.strip_prefix("date:") {
            date = v.trim().to_string();
        } else if let Some(v) = line.strip_prefix("description:") {
            description = v.trim().trim_matches('"').to_string();
        }
    }

    (title, date, description)
}
